const BASE_MS = Date.parse("2026-03-04T09:00:00.000Z");

type EntryInput = {
  id: string;
  minutes: number;
  seconds?: number;
  sessionId?: string | null;
  invocationId?: string | null;
  durationMs?: number | null;
  latencyMs?: number | null;
  ttftMs?: number | null;
  missionId: string;
  missionLabel: string;
  taskId: string;
  taskLabel: string;
  workerId: string;
  workerLabel: string;
  role: LedgerRole;
  provider: string;
  model: string;
  variant?: string | null;
  callIndex: number;
  attempt?: number;
  status?: LedgerCallStatus;
  usage?: LedgerUsage | null;
  usageAuthority: UsageAuthority;
  costMicros?: number | null;
  costProvenance?: CostProvenance;
  attributionConfidence?: AttributionConfidence;
  attributedMissionId?: string | null;
  attributedTaskId?: string | null;
  reconciliation?: ReconciliationStatus;
  note?: string | null;
};

function record(input: EntryInput): ResourceLedgerEntry {
  const elapsedMs = input.minutes * 60_000 + (input.seconds ?? 0) * 1000;
  const timestamp = new Date(BASE_MS + elapsedMs).toISOString();
  const hasTiming = input.durationMs !== undefined && input.durationMs !== null;
  const costProvided = input.costMicros !== undefined && input.costMicros !== null;
  return {
    id: input.id,
    timestamp,
    startedAt: hasTiming ? timestamp : null,
    finishedAt: !hasTiming
      ? null
      : new Date(Date.parse(timestamp) + (input.durationMs ?? 0)).toISOString(),
    sessionId: input.sessionId ?? null,
    invocationId: input.invocationId ?? input.id,
    elapsedMs,
    durationMs: input.durationMs ?? null,
    latencyMs: input.latencyMs ?? null,
    ttftMs: input.ttftMs ?? null,
    missionId: input.missionId,
    missionLabel: input.missionLabel,
    taskId: input.taskId,
    taskLabel: input.taskLabel,
    workerId: input.workerId,
    workerLabel: input.workerLabel,
    role: input.role,
    provider: input.provider,
    model: input.model,
    variant: input.variant ?? null,
    callIndex: input.callIndex,
    attempt: input.attempt ?? 1,
    status: input.status ?? "success",
    usage: input.usage ?? null,
    usageAuthority: input.usageAuthority,
    costMicros: input.costMicros ?? null,
    costProvenance: input.costProvenance ?? (costProvided ? "reported" : "unavailable"),
    attributionConfidence: input.attributionConfidence ?? "exact",
    attributedMissionId: input.attributedMissionId ?? input.missionId,
    attributedTaskId: input.attributedTaskId ?? input.taskId,
    reconciliation: input.reconciliation ?? "reconciled",
    note: input.note ?? null,
  };
}

