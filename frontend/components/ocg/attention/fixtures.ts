/** Fixture queue per scenario. Calm carries history only — zero unresolved. */
export function createAttentionQueue(scenario: ScenarioId): AttentionQueue {
  if (scenario === "attention-calm") {
    return { approvals: [], history: [history()[2]!] };
  }
  if (scenario === "attention-overview") {
    return { approvals: overviewApprovals(), history: history() };
  }
  return { approvals: [], history: [] };
}
