use std::any::TypeId;
use std::collections::{BTreeMap, BTreeSet};
use std::error::Error;
use std::path::Path;

use serde_json::Value;
use ts_rs::{Config, TS, TypeVisitor};

pub fn run() -> Result<(), Box<dyn Error>> {
    let check = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => false,
        [argument] if argument == "--check" => true,
        _ => return Err("usage: ocg-rs-ts [--check]".into()),
    };
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("frontend/components/ocg/contracts/generated.ts");
    let generated = typescript();
    if check {
        if std::fs::read_to_string(&path)? != generated {
            return Err("Control Plane contracts have drifted; run make contracts".into());
        }
    } else {
        std::fs::write(path, generated)?;
    }
    Ok(())
}

pub fn typescript() -> String {
    struct Declarations {
        config: Config,
        seen: BTreeSet<TypeId>,
        output: BTreeMap<String, String>,
    }
    impl TypeVisitor for Declarations {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            if !self.seen.insert(TypeId::of::<T>()) {
                return;
            }
            T::visit_dependencies(self);
            if T::output_path().is_some() {
                self.output
                    .entry(T::ident(&self.config))
                    .or_insert_with(|| T::decl(&self.config));
            }
        }
    }
    let config = Config::new().with_large_int("number");
    let mut output = format!(
        "// Generated by cargo run --bin ocg-rs-ts. Do not edit.\n\nexport const CONTROL_API_VERSION = {} as const;\n\nexport {}\n\n",
        crate::api::v1::API_VERSION,
        Value::decl(&config),
    );
    let mut declarations = Declarations {
        config,
        seen: BTreeSet::from([TypeId::of::<Value>()]),
        output: BTreeMap::new(),
    };
    declarations.visit::<crate::db::entities::AgentCapability>();
    declarations.visit::<crate::db::entities::JobUsage>();
    declarations.visit::<crate::db::entities::JobActivityPhase>();
    declarations.visit::<crate::db::entities::JobActivity>();
    declarations.visit::<crate::db::entities::JobPlanStepView>();
    declarations.visit::<crate::db::entities::JobPlanView>();
    declarations.visit::<crate::db::entities::JobOutputRecord>();
    declarations.visit::<crate::db::entities::LlmParameters>();
    declarations.visit::<crate::api::v1::JobsView>();
    declarations.visit::<crate::api::v1::JobDetailsView>();
    declarations.visit::<crate::api::v1::OutputsView>();
    declarations.visit::<crate::api::v1::ProviderResponsesView>();
    declarations.visit::<crate::api::v1::ToolsView>();
    declarations.visit::<crate::api::v1::HealthView>();
    declarations.visit::<crate::api::v1::UpdateView>();
    declarations.visit::<crate::api::v1::ActiveSystemSettingsView>();
    declarations.visit::<crate::api::v1::AttachmentView>();
    declarations.visit::<crate::api::v1::ProjectsView>();
    declarations.visit::<crate::api::v1::ProjectAnswerView>();
    declarations.visit::<crate::api::v1::PoolsView>();
    declarations.visit::<crate::api::v1::PoolAnswerView>();
    declarations.visit::<crate::api::v1::UsageView>();
    declarations.visit::<crate::api::v1::AvailabilityView>();
    declarations.visit::<crate::api::v1::UsageSummaryView>();
    declarations.visit::<crate::api::v1::UsageBucketsView>();
    declarations.visit::<crate::api::v1::UsageRetriesView>();
    declarations.visit::<crate::api::v1::LogsView>();
    declarations.visit::<crate::api::v1::SessionResponseView>();
    declarations.visit::<crate::api::v1::ConversationsView>();
    declarations.visit::<crate::api::v1::ConversationEditedView>();
    declarations.visit::<crate::api::v1::TurnsView>();
    declarations.visit::<crate::api::v1::ContextStatusView>();
    declarations.visit::<crate::api::v1::AgentProfilesView>();
    declarations.visit::<crate::api::v1::ProfilesView>();
    declarations.visit::<crate::api::v1::ImportedModelsView>();
    declarations.visit::<crate::api::v1::ProviderModelsView>();
    declarations.visit::<crate::api::v1::AdmissionResponseView>();
    declarations.visit::<crate::api::v1::AppendView>();
    declarations.visit::<crate::api::v1::StopView>();
    declarations.visit::<crate::api::v1::CompactionView>();
    declarations.visit::<crate::api::v1::ApprovalDecisionView>();
    declarations.visit::<crate::api::v1::ReleaseSlotView>();
    declarations.visit::<crate::api::v1::CardsView>();
    declarations.visit::<crate::api::v1::ChildrenView>();
    declarations.visit::<crate::api::v1::TreeView>();
    declarations.visit::<crate::api::v1::ConversationLimitsView>();
    declarations.visit::<crate::api::v1::JobInputView>();
    declarations.visit::<crate::api::v1::JobEventView>();
    declarations.visit::<crate::api::v1::OutputEventView>();
    declarations.visit::<crate::api::v1::SettlementEventView>();
    declarations.visit::<crate::api::v1::contracts::GlobalCompactionSettingsInput>();
    declarations
        .output
        .remove(&Value::ident(&declarations.config));
    for declaration in declarations.output.into_values() {
        output.push_str("export ");
        output.push_str(&declaration);
        output.push_str("\n\n");
    }
    let output = output
        .trim_end()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    output + "\n"
}
