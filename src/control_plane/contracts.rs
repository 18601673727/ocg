//! The JSON projections emitted by the Control Plane, independent of storage encoding.

use crate::storage::JobUsage as WireJobUsage;
use serde::Serialize;
use serde_json::Value;
use ts_rs::{Config, TS};

#[derive(Serialize, TS)]
pub(super) struct WireEnvelope<T> {
    pub api_version: u32,
    #[serde(flatten)]
    pub payload: T,
}

pub(super) fn envelope<T: Serialize + TS>(payload: T) -> Value {
    serde_json::json!(WireEnvelope {
        api_version: super::API_VERSION,
        payload
    })
}

// Declaring a projection also registers it for deterministic generation.
macro_rules! contracts {
    ($( $(#[$attr:meta])* $kind:ident $name:ident $body:tt )*) => {
        $(
            #[derive(Serialize, TS)]
            $(#[$attr])*
            pub(super) $kind $name $body
        )*

        /// Generates declarations with JSON numbers and no environment-dependent settings.
        pub fn typescript() -> String {
            let config = Config::new().with_large_int("number");
            let mut output = format!(
                "// Generated by cargo run --bin ocg-rs-ts. Do not edit.\n\nexport const CONTROL_API_VERSION = {} as const;\n\n",
                super::API_VERSION,
            );
            output.push_str("export ");
            output.push_str(&Value::decl(&config));
            output.push_str("\n\n");
            output.push_str("export ");
            output.push_str(&WireJobUsage::decl(&config));
            output.push_str("\n\n");
            output.push_str("export ");
            output.push_str(&WireEnvelope::<Value>::decl(&config));
            output.push_str("\n\n");
            $(
                output.push_str("export ");
                output.push_str(&$name::decl(&config));
                output.push_str("\n\n");
            )*
            let output = output
                .trim_end()
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n");
            output + "\n"
        }
    };
}

